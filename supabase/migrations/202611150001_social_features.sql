-- FilmNegar v1.9 social features
-- Apply this migration once in Supabase SQL Editor. Existing profiles/user_data/shared_lists are preserved.

create table if not exists public.follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  following_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  constraint follows_no_self check (follower_id <> following_id)
);

create index if not exists follows_following_idx on public.follows (following_id, created_at desc);
create index if not exists follows_follower_idx on public.follows (follower_id, created_at desc);

alter table public.follows enable row level security;
drop policy if exists "follows visible to participants" on public.follows;
create policy "follows visible to participants" on public.follows
  for select to authenticated
  using (auth.uid() = follower_id or auth.uid() = following_id);
drop policy if exists "users follow as themselves" on public.follows;
create policy "users follow as themselves" on public.follows
  for insert to authenticated
  with check (auth.uid() = follower_id and follower_id <> following_id);
drop policy if exists "users unfollow as themselves" on public.follows;
create policy "users unfollow as themselves" on public.follows
  for delete to authenticated
  using (auth.uid() = follower_id);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text,
  shared_list jsonb,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint messages_not_self check (sender_id <> recipient_id),
  constraint messages_have_content check (
    nullif(btrim(coalesce(body, '')), '') is not null or shared_list is not null
  )
);

create index if not exists messages_sender_created_idx on public.messages (sender_id, created_at desc);
create index if not exists messages_recipient_created_idx on public.messages (recipient_id, created_at desc);
create index if not exists messages_unread_idx on public.messages (recipient_id, created_at desc) where read_at is null;

alter table public.messages enable row level security;
drop policy if exists "conversation participants read messages" on public.messages;
create policy "conversation participants read messages" on public.messages
  for select to authenticated
  using (auth.uid() = sender_id or auth.uid() = recipient_id);
drop policy if exists "sender creates own messages" on public.messages;
create policy "sender creates own messages" on public.messages
  for insert to authenticated
  with check (auth.uid() = sender_id and sender_id <> recipient_id);
drop policy if exists "recipient marks messages read" on public.messages;
create policy "recipient marks messages read" on public.messages
  for update to authenticated
  using (auth.uid() = recipient_id)
  with check (auth.uid() = recipient_id);

-- Existing profiles are already readable by authenticated users in backend-schema.sql.
-- The messages table intentionally stores a snapshot of shared list items so later edits
-- by the sender cannot silently change the recipient's received list.

-- In-app notifications. A follow event creates a notification for the followed user.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('follow')),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint notifications_not_self check (recipient_id <> actor_id)
);
create index if not exists notifications_recipient_created_idx
  on public.notifications (recipient_id, created_at desc);
create index if not exists notifications_unread_idx
  on public.notifications (recipient_id, created_at desc) where read_at is null;
alter table public.notifications enable row level security;
drop policy if exists "users read own notifications" on public.notifications;
create policy "users read own notifications" on public.notifications
  for select to authenticated using (auth.uid() = recipient_id);
drop policy if exists "users update own notifications" on public.notifications;
create policy "users update own notifications" on public.notifications
  for update to authenticated using (auth.uid() = recipient_id)
  with check (auth.uid() = recipient_id);

create or replace function public.notify_new_follow()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.notifications (recipient_id, actor_id, type)
  values (new.following_id, new.follower_id, 'follow');
  return new;
end;
$$;

drop trigger if exists follows_notify_after_insert on public.follows;
create trigger follows_notify_after_insert
after insert on public.follows
for each row execute function public.notify_new_follow();
